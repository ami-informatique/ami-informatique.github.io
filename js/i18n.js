/* ---------------- Moteur de traduction (ne pas modifier) ---------------- */
(function () {
  var LANGS = ["fr", "en", "ar"];
  var KEY = "ami-lang";

  function choisir() {
    var m = /[?&]lang=(fr|en|ar)\b/.exec(location.search);
    if (m) return m[1];
    try { var s = localStorage.getItem(KEY); if (LANGS.indexOf(s) >= 0) return s; } catch (e) {}
    return "fr";
  }

  var courant = choisir();

  function t(cle, lang) {
    var l = lang || courant;
    var d = I18N[l] || {};
    if (d[cle] != null) return d[cle];
    if (I18N.fr[cle] != null) return I18N.fr[cle];
    return cle;
  }

  function appliquer(lang) {
    if (LANGS.indexOf(lang) < 0) lang = "fr";
    courant = lang;
    var html = document.documentElement;
    html.lang = lang;
    html.dir = lang === "ar" ? "rtl" : "ltr";

    document.querySelectorAll("[data-i18n]").forEach(function (el) {
      el.textContent = t(el.getAttribute("data-i18n"));
    });
    document.querySelectorAll("[data-i18n-html]").forEach(function (el) {
      el.innerHTML = t(el.getAttribute("data-i18n-html"));
    });
    // data-i18n-attr="placeholder:f.optional|aria-label:nav.open"
    document.querySelectorAll("[data-i18n-attr]").forEach(function (el) {
      el.getAttribute("data-i18n-attr").split("|").forEach(function (paire) {
        var p = paire.split(":");
        if (p.length === 2) el.setAttribute(p[0].trim(), t(p[1].trim()));
      });
    });
    // Blocs de texte longs écrits directement en 3 langues (pages de confidentialité)
    document.querySelectorAll("[data-lang-block]").forEach(function (el) {
      el.hidden = el.getAttribute("data-lang-block") !== lang;
    });
    document.querySelectorAll("[data-set-lang]").forEach(function (b) {
      b.setAttribute("aria-pressed", b.getAttribute("data-set-lang") === lang ? "true" : "false");
    });
    document.querySelectorAll("[data-lang-current]").forEach(function (el) {
      el.textContent = lang === "ar" ? "ع" : lang.toUpperCase();
    });

    try { localStorage.setItem(KEY, lang); } catch (e) {}
    document.dispatchEvent(new CustomEvent("langchange", { detail: { lang: lang } }));
  }

  // Sélecteur de langue (bouton + menu)
  function initSelecteur() {
    document.querySelectorAll(".lang").forEach(function (box) {
      var btn = box.querySelector(".lang-btn");
      var menu = box.querySelector(".lang-menu");
      if (!btn || !menu) return;
      function fermer() { menu.hidden = true; btn.setAttribute("aria-expanded", "false"); }
      btn.addEventListener("click", function (e) {
        e.stopPropagation();
        var ouvrir = menu.hidden;
        menu.hidden = !ouvrir;
        btn.setAttribute("aria-expanded", ouvrir ? "true" : "false");
      });
      menu.querySelectorAll("[data-set-lang]").forEach(function (b) {
        b.addEventListener("click", function () { appliquer(b.getAttribute("data-set-lang")); fermer(); btn.focus(); });
      });
      document.addEventListener("click", function (e) { if (!box.contains(e.target)) fermer(); });
      document.addEventListener("keydown", function (e) { if (e.key === "Escape") fermer(); });
    });
  }

  window.AMI_I18N = {
    t: t,
    set: appliquer,
    get lang() { return courant; }
  };

  initSelecteur();
  appliquer(courant);
})();
